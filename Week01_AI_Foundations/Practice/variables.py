# 1. String variable
name = "Jayasri"
print("Name:", name)

# 2. Integer variable
age = 22
print("Age:", age)

# 3. Float variable
height = 5.4
print("Height:", height)

# 4. Boolean variable
is_student = True
print("Is Student:", is_student)

# 5. Checking data types
print("\nData Types:")
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))

# 6. Multiple variables
first_name = "Jayasri"
last_name = "G"

print("\nFull Name:", first_name, last_name)

# 7. Changing a variable
age = 23
print("Updated Age:", age)

# 8. Simple calculation using variables
a = 10
b = 20

sum_result = a + b

print("\nSum:", sum_result)

# 9. Taking input from user
user_name = input("\nEnter your name: ")
print("Hello", user_name)
a = 20
b = 5

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Floor Division
print("Floor Division:", a // b)

# Modulus - remainder
print("Remainder:", a % b)

# Power
print("Power:", a ** b)

# Order of operations
result = 10 + 5 * 2
print("Order of operations:", result)